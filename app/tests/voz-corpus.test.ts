// Corpus grande de cierres dichos en voz alta, tal como los escribe el dictado del celular (Android/iPhone).
// Cada caso: [frase, ventas, cobrado con tarjeta/QR, gastos por categoría]. Si una frase falla, el lector está mal, no la frase.
type G = Partial<Record<"proveedor" | "flete" | "vuelto" | "otros", number>>;
type Caso = [string, number, number, G];

const leer = (t: string) => {
  const r = entenderCierre(t, []);
  return { ventas: r.ventas, tarjeta: r.tarjeta, gastos: Object.fromEntries(r.gastos.map((x) => [x.categoria, x.monto])) };
};

